-module(arizona_html_entities).
-moduledoc """
The HTML named character references, as the WHATWG HTML standard lists them (a frozen
list: no name is ever added), every name
the tokenizer decodes, the ones it also accepts without a trailing `;` (the legacy
names) included, each with the text it stands for.

`arizona_html` decodes markup with it where it must read a value the way the browser
does: an `<option>` a component or `?raw` markup renders under a `<select>` that has
a value (`arizona_html:mark_choices/2`), and the text of an option valued by its text,
static (folded at compile time) or rendered by a value in it
(`arizona_html:markup_text/1`), each of which can be written with any of them. The
table is a literal: in interactive mode the module loads on the first reference looked
up, while an embedded release loads it at boot with every other module.
""".

-export([named/1]).

-doc """
The text the named reference `Name` stands for: `Name` is what follows the `&`, with
its `;` when the reference has one (`~"eacute;"`), without it for a legacy one
(`~"eacute"`).
""".
-spec named(Name) -> {ok, Text} | error when
    Name :: binary(),
    Text :: binary().
named(Name) ->
    case table() of
        #{Name := Text} -> {ok, Text};
        #{} -> error
    end.

