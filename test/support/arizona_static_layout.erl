-module(arizona_static_layout).
-moduledoc """
Fixture: the shell of a page generated by `arizona_static` and served as a plain
file, with no server behind it. It loads the static client and calls `start()`,
which delegates the event names `arizona_static` embedded in the page.
""".
-include("arizona_stateless.hrl").
-export([render/1]).

-spec render(az:bindings()) -> az:template().
render(Bindings) ->
    ?html([
        ~"<!DOCTYPE html>",
        {html, [], [
            {head, [], [{meta, [{charset, ~"utf-8"}], []}, {title, [], [~"Static"]}]},
            {body, [], [
                ?inner_content,
                {script, [{type, ~"module"}], [
                    ~"""
                    import { start } from '/priv/arizona-static.min.js';
                    start();
                    """
                ]}
            ]}
        ]}
    ]).
